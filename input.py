# learning input function in python programming
# The input() function allows user input from the console.
# This file demonstrates how to use the input() function to get user data.
# Example: Getting user's name and age
# Getting user's name
user_name = input("Enter your name: ")
print("Hello, " + user_name + "!")

# Getting user's age
user_age = input("Enter your age: ")
print("You are " + user_age + " years old.")

# Getting user's height
user_height = input("Enter your height in feet: ")
print("Your height is " + user_height + " feet.")

# Getting user's favorite color
favorite_color = input("Enter your favorite color: ")
print("Your favorite color is " + favorite_color + ".")
